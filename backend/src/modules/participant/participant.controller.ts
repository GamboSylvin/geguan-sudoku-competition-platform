/**
 * HTTP layer for the Participant module (Unit 04). It validates input, then calls the
 * service; no domain rule lives here.
 *
 * The six endpoints of the spec's API contract, all mounted under
 * `/api/competitions/:id` (see `routes.ts`, the same mergeParams pattern Unit 05 uses),
 * so `:id` comes from the path:
 * - `POST   /participants/import`   — multipart upload of one `.xlsx`, atomic
 * - `GET    /participants`          — the roster and its counts, never a password
 * - `POST   /participants`          — add one by hand (PAR-003)
 * - `PATCH  /participants/:pid`     — edit one; a name change issues new credentials
 * - `DELETE /participants/:pid`     — deactivate, never hard-delete
 * - `GET    /participants/credentials` — download the printable slips `.xlsx`
 *
 * Every one is controller-only (ROL-002, spec Security Considerations): this is the
 * module that mints player logins, so no other role may reach it.
 *
 * The upload deliberately does **not** use a multipart middleware package: `app.ts`
 * parses JSON bodies globally, and this route asks Express for the raw bytes of a
 * `multipart/form-data` body instead, which the question module's generic
 * `readUploadedFile` then splits. No new dependency (code-standards.md, Dependencies).
 */
import { Router, type NextFunction, type Request, type Response } from "express";
import express from "express";
import { z } from "zod";
import { AppError, ForbiddenError } from "../../shared/errors";
import { translate } from "../../shared/i18n";
import { requireAuth } from "../../shared/middleware";
import { parseInput } from "../../shared/validation";
import { participantService } from "./participant.service";
import type { UploadedParticipantFile } from "./participant.service";

/** Only a controller may import participants or read their credentials. */
function requireController(req: Request, _res: Response, next: NextFunction): void {
  if (req.auth?.role !== "CONTROLLER") {
    next(
      new ForbiddenError(translate("en", "participant.forbidden"), {
        code: "participant.forbidden",
      }),
    );
    return;
  }
  next();
}

const paramsSchema = z.object({ id: z.string().min(1) });
const participantParamsSchema = paramsSchema.extend({ participantId: z.string().min(1) });

/**
 * The list's optional filters. Both are plain pass-throughs to the service; `active`
 * matters because the setup screen shows the deactivated rows too and the round's field is
 * only the `individualEvent` ones (spec §8 Q3).
 */
const listQuerySchema = z.object({
  active: z
    .enum(["true", "false"])
    .optional()
    .transform((value) => (value === undefined ? undefined : value === "true")),
  categoryId: z.string().min(1).optional(),
});

const addSchema = z.object({
  name: z.string(),
  categoryId: z.string().min(1),
  schoolName: z.string(),
  // Both flags default to the file's own "not participating" reading, so a hand-add that
  // omits them behaves like a blank cell rather than like a `1` (spec §8 Q3).
  individualEvent: z.boolean().default(false),
  teamEvent: z.boolean().default(false),
});

const editSchema = z
  .object({
    name: z.string().min(1).optional(),
    categoryId: z.string().min(1).optional(),
    schoolId: z.string().min(1).optional(),
    schoolName: z.string().min(1).optional(),
    teamId: z.string().min(1).nullable().optional(),
    participantNumber: z.number().int().positive().optional(),
    active: z.boolean().optional(),
    individualEvent: z.boolean().optional(),
    teamEvent: z.boolean().optional(),
  })
  // An empty body would be a silent no-op, which reads like a success to the caller and
  // hides a form that failed to serialize. Rejecting it makes that visible.
  .refine((value) => Object.keys(value).length > 0, {
    message: "no editable field given",
  });

/** The raw multipart body Express hands over, plus its boundary. */
function readUpload(req: Request): UploadedParticipantFile | null {
  const contentType = req.get("content-type") ?? "";
  const boundary = /boundary=(?:"([^"]*)"|([^;]*))/i.exec(contentType);
  const value = (boundary?.[1] ?? boundary?.[2])?.trim();
  if (!value || !Buffer.isBuffer(req.body)) return null;
  return { body: req.body as Buffer, boundary: value };
}

/**
 * A file download. The name is ASCII-only on purpose: the slips file's own name is
 * generated by the service and is already ASCII, and an unencoded non-ASCII
 * `Content-Disposition` would corrupt the header.
 */
function sendFile(res: Response, bytes: Buffer, originalName: string, mimeType: string): void {
  res.setHeader("Content-Type", mimeType);
  res.setHeader("Content-Length", String(bytes.length));
  res.setHeader("Content-Disposition", `attachment; filename="${originalName}"`);
  res.status(200).send(bytes);
}

export const participantRouter = Router({ mergeParams: true });

const rawUpload = express.raw({ type: "multipart/form-data", limit: "20mb" });

participantRouter.post(
  "/participants/import",
  requireAuth,
  requireController,
  rawUpload,
  async (req, res, next) => {
    try {
      const { id } = parseInput(paramsSchema, req.params);
      const upload = readUpload(req);
      if (!upload) {
        // Not a 422 from the parser: the request itself carries no file part.
        throw new AppError(translate("en", "participant.import.noFile"), {
          statusCode: 400,
          code: "participant.import.noFile",
        });
      }
      const result = await participantService.importParticipantFile({
        competitionId: id,
        upload,
        uploadedByAccountId: req.auth?.accountId ?? null,
      });
      res.status(200).json(result);
    } catch (error) {
      next(error);
    }
  },
);

participantRouter.get("/participants", requireAuth, requireController, async (req, res, next) => {
  try {
    const { id } = parseInput(paramsSchema, req.params);
    const filter = parseInput(listQuerySchema, req.query);
    res.status(200).json(await participantService.listParticipants(id, filter));
  } catch (error) {
    next(error);
  }
});

/**
 * Declared before `/:participantId` so `credentials` is not swallowed as an id. Express
 * matches in registration order, and `GET /participants/credentials` would otherwise
 * arrive at the participant route with `participantId = "credentials"`.
 */
participantRouter.get(
  "/participants/credentials",
  requireAuth,
  requireController,
  async (req, res, next) => {
    try {
      const { id } = parseInput(paramsSchema, req.params);
      const file = await participantService.exportCredentials({
        competitionId: id,
        uploadedByAccountId: req.auth?.accountId ?? null,
      });
      sendFile(res, file.bytes, file.originalName, file.mimeType);
    } catch (error) {
      next(error);
    }
  },
);

participantRouter.post("/participants", requireAuth, requireController, async (req, res, next) => {
  try {
    const { id } = parseInput(paramsSchema, req.params);
    const body = parseInput(addSchema, req.body);
    res.status(201).json(await participantService.addParticipant({ competitionId: id, ...body }));
  } catch (error) {
    next(error);
  }
});

participantRouter.patch(
  "/participants/:participantId",
  requireAuth,
  requireController,
  async (req, res, next) => {
    try {
      const { id, participantId } = parseInput(participantParamsSchema, req.params);
      const edit = parseInput(editSchema, req.body);
      res
        .status(200)
        .json(await participantService.editParticipant({ competitionId: id, participantId, edit }));
    } catch (error) {
      next(error);
    }
  },
);

participantRouter.delete(
  "/participants/:participantId",
  requireAuth,
  requireController,
  async (req, res, next) => {
    try {
      const { id, participantId } = parseInput(participantParamsSchema, req.params);
      await participantService.deactivateParticipant(id, participantId);
      // 204 rather than 20-with-body: the row is deactivated, not deleted, and the list
      // endpoint is the authoritative view of what remains active.
      res.status(204).send();
    } catch (error) {
      next(error);
    }
  },
);
