/**
 * The domain rules of the Competition module and its public interface (Unit 03).
 * Other modules call this service, never the repository (invariant 4).
 *
 * What lives here: creating a competition and auto-building its fixed 2-stage ×
 * 2-round structure with the documented defaults, editing it before publish, the
 * four-condition publish readiness check, publishing, and the structure lock.
 *
 * Two decisions worth stating:
 * - The stages are the schema's: exactly two per *competition* (Individual then
 *   Team), with round settings set once per round for the whole event, not per
 *   category (data-model.md, RND-005; CS-010). Categories are created alongside;
 *   they run in parallel against the same structure.
 * - The two link tokens are generated by the schema's `@default(uuid())` when the
 *   competition row is created, so publish surfaces them rather than creating them
 *   (Unit 03 spec, Implementation Details 4).
 */
