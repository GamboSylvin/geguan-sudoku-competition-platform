/**
 * The fixed structure every competition gets: two stages (Individual, Team), each
 * with two rounds, each round's settings at their documented defaults, including
 * the schema-required `durationSeconds` (1200 / 1800 / 1800 / 1800).
 */
function buildStructure(): repository.StageStructureInput[] {
  return STAGE_SEQUENCE.map((type, stageIndex) => ({
    type,
    sequence: stageIndex + 1,
    rounds: Array.from({ length: STAGE_ROUND_COUNT }, (_unused, roundIndex) => {
      const sequence = roundIndex + 1;
      return {
        sequence,
        name: ROUND_NAME[`${type}:${sequence}`] ?? `${type} round ${sequence}`,
        durationSeconds: defaultDurationSeconds(type, sequence),
      };
    }),
  }));
}

/** Normalize the input category list into the ordered rows to create. */
function buildCategories(categories: CategoryInput[]): repository.CategoryStructureInput[] {
  return categories.map((category, index) => ({
    code: category.code,
    name: category.name,
    sequence: index + 1,
  }));
}

export async function createCompetition(
  input: CreateCompetitionInput,
): Promise<CompetitionWithStructure> {
  if (input.categories.length === 0) {
    // The controller's schema also rejects this; the rule lives here too.
    throw new ValidationError("At least one category is required", {
      categories: "must contain at least one category",
    });
  }

  return repository.createCompetition({
    name: input.name,
    description: input.description ?? null,
    categories: buildCategories(input.categories),
    stages: buildStructure(),
    ...(input.scoringConfiguration !== undefined
      ? { scoringConfiguration: input.scoringConfiguration }
      : {}),
  });
}

// ---------------------------------------------------------------------------
// Editing (pre-publish for the structure; round settings per the existing rule)
// ---------------------------------------------------------------------------

/**
 * Edit a competition. Name/description and the category list are pre-publish only
 * (the structure is locked after publish); round-settings edits are allowed any time
 * within this unit's scope (the per-round-preparation cutoff is Unit 07's).
 */
export async function updateCompetition(
  id: string,
  input: UpdateCompetitionInput,
): Promise<CompetitionWithStructure> {
  const existing = await repository.findCompetitionById(id);
  if (!existing) {
    throw notFoundError();
  }

  const locked = isStructureLocked(existing.status);

  // Name and description are metadata, not structure — they stay editable.
  if (input.name !== undefined || input.description !== undefined) {
    await repository.updateCompetitionMeta(id, {
      ...(input.name !== undefined ? { name: input.name } : {}),
      ...(input.description !== undefined ? { description: input.description } : {}),
    });
  }

  if (input.categories !== undefined) {
    if (locked) {
      throw lockedError();
    }
    await applyCategoryChanges(id, existing, input.categories);
  }

  if (input.roundSettings !== undefined) {
    for (const [roundId, patch] of Object.entries(input.roundSettings)) {
      await updateRoundSettings(id, roundId, patch);
    }
  }

  // Scoring configuration (BLD-051): a value, not structure, so it is editable at any
  // status — the same latitude round settings already have. An empty object changes
  // nothing, so it is skipped rather than issuing a no-op write.
  if (input.scoringConfiguration !== undefined) {
    const scoring = input.scoringConfiguration;
    if (scoring.schoolCoefficient !== undefined || scoring.rankingCycleSeconds !== undefined) {
      await repository.updateScoringConfiguration(id, scoring);
    }
  }

  const updated = await repository.findCompetitionById(id);
  if (!updated) {
    throw notFoundError();
  }
  return updated;
}

/** Work out the add/remove/reorder plan by matching categories on their code. */
async function applyCategoryChanges(
  competitionId: string,
  existing: CompetitionWithStructure,
  categories: CategoryInput[],
): Promise<void> {
  const wantedCodes = new Set(categories.map((category) => category.code));
  const deleteIds = existing.categories
    .filter((category) => !wantedCodes.has(category.code))
    .map((category) => category.id);

  const byCode = new Map(existing.categories.map((category) => [category.code, category]));
  const create: repository.CategoryStructureInput[] = [];
  const update: { id: string; name: string; sequence: number }[] = [];

  categories.forEach((category, index) => {
    const current = byCode.get(category.code);
    if (current) {
      update.push({ id: current.id, name: category.name, sequence: index + 1 });
    } else {
      create.push({ code: category.code, name: category.name, sequence: index + 1 });
    }
  });

  await repository.applyCategoryChanges(competitionId, { create, update, deleteIds });
}

/** Edit one round's numeric settings, after checking the round belongs to this competition. */
async function updateRoundSettings(
  competitionId: string,
  roundId: string,
  patch: RoundSettingsPatch,
): Promise<void> {
  const round = await repository.findRoundWithCompetition(roundId);
  if (!round || round.stage.competitionId !== competitionId) {
    throw notFoundError();
  }
  validateRoundSettingsPatch(patch);
  if (Object.keys(patch).length > 0) {
    await repository.updateRoundSettings(roundId, patch);
  }
}

// ---------------------------------------------------------------------------
// Publish readiness (four named conditions; later units add their own)
// ---------------------------------------------------------------------------

/**
 * Evaluate the four readiness conditions and return every unmet one (not just the
 * first). The result is a list, so a later unit can plug its condition in here.
 */
export async function checkPublishReadiness(
  competitionId: string,
): Promise<ReadinessResult> {
  const competition = await repository.findCompetitionById(competitionId);
  if (!competition) {
    throw notFoundError();
  }

  const unmet: ReadinessCondition[] = [];

  // 1. At least one category.
  if (competition.categories.length === 0) {
    unmet.push(condition("competition.readiness.categoryRequired"));
  }

  // 2. Every category has at least one participant.
  const participantCategoryIds = new Set(
    (await repository.listActiveParticipantCategoryIds(competitionId)).map(
      (row) => row.categoryId,
    ),
  );
  if (competition.categories.some((c) => !participantCategoryIds.has(c.id))) {
    unmet.push(condition("competition.readiness.participantsRequired"));
  }

  // 3. Every category has a complete question selection for **every** round — both
  // Individual rounds *and* both Team rounds (BLD-040, revised 2026-10-19). This used to
  // look only at `stage.type === "INDIVIDUAL"`, which is exactly what made the Team
  // stage look like a missing feature: the Questions panel offered two rounds while the
  // publish rejection was read as being about all four. `Question.roundId` is nullable,
  // so an imported question sits in the pool unassigned until the controller's selection
  // step assigns the round's own count (6, 10 or 3 — see `roundQuestionTarget`).
  // "Covered" therefore means that round's full count is assigned, not merely that some
  // question references it.
  const allRounds = competition.stages.flatMap((stage) =>
    stage.rounds.map((round) => ({
      id: round.id,
      name: round.name,
      sequence: round.sequence,
      stageType: stage.type as string,
      settings: round.settings,
    })),
  );
  if (allRounds.length === 0) {
    unmet.push(condition("competition.readiness.questionsRequired"));
  } else {
    // Collect every short round of every category instead of stopping at the first, so
    // one rejection names the whole gap. A single condition is pushed, because the
    // controller renders each condition as a list item keyed by its `key` — pushing one
    // per incomplete round would repeat that key.
    const roundNames = new Map(allRounds.map((round) => [round.id, round.name]));
    const roundTargets = new Map(allRounds.map((round) => [round.id, roundQuestionTarget(round)]));
    const short: string[] = [];
    for (const category of competition.categories) {
      const countByRound = new Map(
        (await repository.countCategoryQuestionsPerRound(category.id)).map((row) => [
          row.roundId,
          row.count,
        ]),
      );
      for (const round of allRounds) {
        const target = roundTargets.get(round.id) ?? INDIVIDUAL_ROUND_QUESTION_COUNT;
        const count = countByRound.get(round.id) ?? 0;
        if (count !== target) {
          short.push(
            `${category.name} · ${roundNames.get(round.id) ?? round.id}: ${count} / ${target}`,
          );
        }
      }
    }
    if (short.length > 0) {
      unmet.push(
        conditionWith("competition.readiness.questionsRequired", short.join("; ")),
      );
    }
  }

  // 4. Judge ranges cover every active participant number.
  const participantNumbers = (
    await repository.listActiveParticipantNumbers(competitionId)
  ).map((row) => row.participantNumber);
  if (participantNumbers.length > 0) {
    const ranges = await repository.listJudgeRanges(competitionId);
    const uncovered = participantNumbers.some(
      (number) =>
        !ranges.some(
          (range) =>
            number >= range.fromParticipantNumber && number <= range.toParticipantNumber,
        ),
    );
    if (uncovered) {
      unmet.push(condition("competition.readiness.judgeRangesRequired"));
    }
  }

  return { ready: unmet.length === 0, unmet };
}

