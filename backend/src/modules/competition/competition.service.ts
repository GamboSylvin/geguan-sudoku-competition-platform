// ---------------------------------------------------------------------------

/**
 * Publish the competition. Refuses with the specific unmet conditions (HTTP 422,
 * handled by the controller) and makes no state change if any fails; otherwise moves
 * the status `PUBLISHED` → `WAITING`, sets `publishedAt`, and returns the two links
 * that already exist. Publishing more than once is rejected.
 */
export async function publishCompetition(id: string): Promise<PublishResult> {
  const competition = await repository.findCompetitionById(id);
  if (!competition) {
    throw notFoundError();
  }

  if (isStructureLocked(competition.status)) {
    // Already published (or beyond): publishing again is not allowed.
    throw new ConflictError("This competition is already published.", {
      code: "competition.alreadyPublished",
      details: { status: competition.status },
    });
  }

  const readiness = await checkPublishReadiness(id);
  if (!readiness.ready) {
    throw new UnprocessableEntityError("The competition is not ready to publish.", {
      code: "competition.notReady",
      details: { unmet: readiness.unmet },
    });
  }

  const publishedAt = now();
  const updated = await repository.markPublished(id, publishedAt);

  return {
    id: updated.id,
    status: updated.status,
    publishedAt: updated.publishedAt?.toISOString() ?? publishedAt.toISOString(),
    entryLinkToken: updated.entryLinkToken,
    bigScreenLinkToken: updated.bigScreenLinkToken,
    ...competitionLinks(updated),
  };
}

